"""Turn --endless-check output into scripts/game/endless_table.gd.

    godot --headless --path . -- --endless-check [--part=k/n] > check_k.log
    python3 tools/endless/make_table.py check_*.log

Each ENDLESS line is one stretch at one speed. The table keeps, per stretch and speed:
ok [clear, rain, wind], the bot's time through it [clear, rain, wind], its length in px,
the careful rider's timing windows (ms) and the tightest one ("min").
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "scripts", "game", "endless_table.gd")


def main(paths):
    table = {}
    for p in paths:
        for line in open(p):
            if not line.startswith("ENDLESS {"):
                continue
            r = json.loads(line[8:])
            table.setdefault(r["key"], {})[str(r["tier"])] = {
                "ok": r["ok"], "t": r["t"], "len": r["len"], "w": r["w"], "min": r["min"]}
    out = ["## Generated by tools/endless/make_table.py from --endless-check. Do not edit.",
           "## key -> speed -> {ok [clear, rain, wind], t [s], len px, w [window ms], min ms}",
           "extends RefCounted", "", "const T := {"]
    for key in sorted(table):
        out.append('\t"%s": {' % key)
        for tier in sorted(table[key], key=int):
            e = table[key][tier]
            ok = ", ".join("true" if v else "false" for v in e["ok"])
            t = ", ".join("%.2f" % v for v in e["t"])
            w = ", ".join(str(int(v)) for v in e["w"])
            out.append('\t\t"%s": {"ok": [%s], "t": [%s], "len": %.1f, "w": [%s], "min": %d},'
                       % (tier, ok, t, e["len"], w, e["min"]))
        out.append("\t},")
    out.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    n = sum(len(v) for v in table.values())
    safe = sum(1 for v in table.values() for e in v.values() if e["ok"][0] and e["min"] >= 75)
    print(f"{len(table)} stretches, {n} stretch-speeds, {safe} safe in clear -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1:])
